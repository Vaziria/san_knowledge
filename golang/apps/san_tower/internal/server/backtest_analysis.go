// rememberFolder puts dir first in the recent folders (tower.json).
func (s *Server) rememberFolder(dir string) ([]string, error) {
	var out []string
	err := settings.Update(s.store.Dir(), func(st *settings.Settings) {
		if st.BacktestAnalysis == nil {
			st.BacktestAnalysis = &settings.BacktestAnalysis{}
		}
		recent := []string{dir}
		for _, p := range st.BacktestAnalysis.Recent {
			if !strings.EqualFold(p, dir) && len(recent) < maxRecentFolders {
				recent = append(recent, p)
			}
		}
		st.BacktestAnalysis.Recent = recent
		out = recent
	})
	return out, err
}

func (s analysisService) ListRecentFolders(_ context.Context, req *connect.Request[v1.BacktestListRecentFoldersRequest]) (*connect.Response[v1.BacktestListRecentFoldersResponse], error) {
	if !fromThisComputer(req.Peer()) {
		return nil, errNotLocal
	}
	st, err := settings.Load(s.store.Dir())
	if err != nil {
		return nil, connect.NewError(connect.CodeInternal, err)
	}
	res := &v1.BacktestListRecentFoldersResponse{}
	if st.BacktestAnalysis != nil {
		res.Folders = st.BacktestAnalysis.Recent
	}
	return connect.NewResponse(res), nil
}

func (s analysisService) ForgetRecentFolder(_ context.Context, req *connect.Request[v1.BacktestForgetRecentFolderRequest]) (*connect.Response[v1.BacktestForgetRecentFolderResponse], error) {
	if !fromThisComputer(req.Peer()) {
		return nil, errNotLocal
	}
	var out []string
	err := settings.Update(s.store.Dir(), func(st *settings.Settings) {
		if st.BacktestAnalysis == nil {
			return
		}
		var keep []string
		for _, p := range st.BacktestAnalysis.Recent {
			if !strings.EqualFold(p, req.Msg.GetPath()) {
				keep = append(keep, p)
			}
		}
		st.BacktestAnalysis.Recent = keep
		out = keep
	})
	if err != nil {
		return nil, connect.NewError(connect.CodeInternal, err)
	}
	return connect.NewResponse(&v1.BacktestForgetRecentFolderResponse{Folders: out}), nil
}

// WatchFolder sends the folder's reports, then reads it again every
// analysisPoll and sends the reports that appeared, changed (a newer file,
// or run.json now there) or went away, so a backtest writing into an open
// folder shows by itself.
func (s analysisService) WatchFolder(ctx context.Context, req *connect.Request[v1.BacktestWatchFolderRequest], stream *connect.ServerStream[v1.BacktestWatchFolderResponse]) error {
	if !fromThisComputer(req.Peer()) {
		return errNotLocal
	}
	snap, err := scanFolder(req.Msg.GetPath())
	if err != nil {
		return err
	}
	if err := stream.Send(&v1.BacktestWatchFolderResponse{Event: &v1.BacktestWatchFolderResponse_Snapshot{Snapshot: snap}}); err != nil {
		return err
	}
	known := map[string]*v1.BacktestRunSummary{}
	for _, r := range snap.Runs {
		known[r.Path] = r
	}
	poll := time.NewTicker(analysisPoll)
	defer poll.Stop()
	beat := time.NewTicker(watchHeartbeat)
	defer beat.Stop()
	for {
		select {
		case <-ctx.Done():
			return nil
		case <-s.analysisStop:
			return nil // the tower stops
		case <-beat.C:
			if err := stream.Send(&v1.BacktestWatchFolderResponse{Event: &v1.BacktestWatchFolderResponse_Heartbeat{Heartbeat: true}}); err != nil {
				return err
			}
		case <-poll.C:
			now, err := scanFolder(snap.Path)
			if err != nil {
				continue // the folder is gone for now: keep what the page has
			}
			seen := map[string]bool{}
			for _, r := range now.Runs {
				seen[r.Path] = true
				if old, ok := known[r.Path]; ok && proto.Equal(old, r) {
					continue
				}
				known[r.Path] = r
				if err := stream.Send(&v1.BacktestWatchFolderResponse{Event: &v1.BacktestWatchFolderResponse_Changed{Changed: r}}); err != nil {
					return err
				}
			}
			for p := range known {
				if !seen[p] {
					delete(known, p)
					if err := stream.Send(&v1.BacktestWatchFolderResponse{Event: &v1.BacktestWatchFolderResponse_Removed{Removed: p}}); err != nil {
						return err
					}
				}
			}
		}
	}
}
