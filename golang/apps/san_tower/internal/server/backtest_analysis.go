	if !fromThisComputer(req.Peer()) {
		return nil, errNotLocal
	}
	res, err := s.paperRuns()
	if err != nil {
		return nil, connect.NewError(connect.CodeInternal, err)
	}
	return connect.NewResponse(res), nil
