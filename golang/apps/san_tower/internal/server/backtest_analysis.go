// BacktestAnalysisService: the Backtest Analysis page opens folders of San
// Backtest reports read-only (the user, 2026-11-15: "It can open directory
// that contain report log that generated by backtest"; "1a": the page only
// opens reports and starts no runs). The reading is in
// internal/backtestanalysis; here are the RPCs, the recent folders (in
// tower.json) and the folder watch.

// analysisService answers BacktestAnalysisService. It is a type of its own
// because WorkflowService, which Server answers, has a GetRun and a
// ListFolders too.
type analysisService struct{ *Server }

var _ towerv1connect.BacktestAnalysisServiceHandler = analysisService{}

// maxRecentFolders is how many opened folders the page remembers.
const maxRecentFolders = 10

// analysisPoll is how often WatchFolder reads its folder again.
var analysisPoll = 3 * time.Second

// errNotLocal refuses a caller on another computer: the service names this
// computer's paths, so it answers only on it, also with serve --lan.
var errNotLocal = connect.NewError(connect.CodePermissionDenied, errors.New("Backtest Analysis reads this computer's folders: open it on the tower's own computer"))

// fromThisComputer says whether a call came over loopback. A peer address
// that cannot be read counts as remote.
func fromThisComputer(peer connect.Peer) bool {
	host, _, err := net.SplitHostPort(peer.Addr)
	if err != nil {
		host = peer.Addr
	}
	ip := net.ParseIP(strings.Trim(host, "[]"))
	return ip != nil && ip.IsLoopback()
}

func analysisError(err error) error {
	var ce *connect.Error
	switch {
	case errors.As(err, &ce):
		return err
	case errors.Is(err, fs.ErrNotExist):
		return connect.NewError(connect.CodeNotFound, err)
	case errors.Is(err, fs.ErrPermission):
		return connect.NewError(connect.CodePermissionDenied, err)
	case errors.Is(err, backtestanalysis.ErrNotReport):
		return connect.NewError(connect.CodeInvalidArgument, err)
	}
	return connect.NewError(connect.CodeInvalidArgument, err)
}

// reportDir checks a report path: absolute, a report folder; or a paper
// session's "paper:<id>", made into its report folder.
func (s analysisService) reportDir(path string) (string, error) {
	if dir, _, ok, err := s.paperDir(path); ok {
		return dir, err
	}
	return reportDir(path)
}

// reportDir checks a report path: absolute, a report folder.
func reportDir(path string) (string, error) {
	dir, err := backtestanalysis.Clean(path)
	if err != nil {
		return "", connect.NewError(connect.CodeInvalidArgument, err)
	}
	if st, err := os.Stat(dir); err != nil {
		return "", analysisError(err)
	} else if !st.IsDir() {
		return "", connect.NewError(connect.CodeInvalidArgument, errors.New(dir+" is not a folder"))
	}
	if !backtestanalysis.IsReport(dir) {
		return "", connect.NewError(connect.CodeInvalidArgument, errors.New(dir+": "+backtestanalysis.ErrNotReport.Error()))
	}
	return dir, nil
}

func (s analysisService) ListFolders(_ context.Context, req *connect.Request[v1.BacktestListFoldersRequest]) (*connect.Response[v1.BacktestListFoldersResponse], error) {
	if !fromThisComputer(req.Peer()) {
		return nil, errNotLocal
	}
	res, err := backtestanalysis.Folders(req.Msg.GetPath())
	if err != nil {
		return nil, analysisError(err)
	}
	return connect.NewResponse(res), nil
}

func scanFolder(path string) (*v1.BacktestOpenFolderResponse, error) {
	dir, err := backtestanalysis.Clean(path)
	if err != nil {
		return nil, connect.NewError(connect.CodeInvalidArgument, err)
	}
	runs, truncated, err := backtestanalysis.Scan(dir)
	if err != nil {
		return nil, analysisError(err)
	}
	return &v1.BacktestOpenFolderResponse{Path: dir, Runs: runs, Truncated: truncated}, nil
}

func (s analysisService) OpenFolder(_ context.Context, req *connect.Request[v1.BacktestOpenFolderRequest]) (*connect.Response[v1.BacktestOpenFolderResponse], error) {
	if !fromThisComputer(req.Peer()) {
		return nil, errNotLocal
	}
	res, err := scanFolder(req.Msg.GetPath())
	if err != nil {
		return nil, err
	}
	if _, err := s.rememberFolder(res.Path); err != nil {
		return nil, connect.NewError(connect.CodeInternal, err)
	}
	return connect.NewResponse(res), nil
}

func (s analysisService) GetRun(_ context.Context, req *connect.Request[v1.BacktestGetRunRequest]) (*connect.Response[v1.BacktestGetRunResponse], error) {
	if !fromThisComputer(req.Peer()) {
		return nil, errNotLocal
	}
	dir, err := s.reportDir(req.Msg.GetPath())
	if err != nil {
		return nil, err
	}
	run, err := backtestanalysis.Run(dir, int(req.Msg.GetEquityPoints()))
	if err != nil {
		return nil, analysisError(err)
	}
	run.Summary.RelPath = filepath.Base(dir)
	if id, ok := backtestanalysis.PaperID(req.Msg.GetPath()); ok {
		if p, err := s.live.Session(id); err == nil {
			backtestanalysis.PaperSummary(run.Summary, id, p.Name, p.Status)
		}
	}
	return connect.NewResponse(&v1.BacktestGetRunResponse{Run: run}), nil
}

func (s analysisService) GetCandles(_ context.Context, req *connect.Request[v1.BacktestGetCandlesRequest]) (*connect.Response[v1.BacktestGetCandlesResponse], error) {
	if !fromThisComputer(req.Peer()) {
		return nil, errNotLocal
	}
	dir, err := s.reportDir(req.Msg.GetPath())
	if err != nil {
		return nil, err
	}
	m := req.Msg
	var from, to time.Time
	if m.From != nil {
		from = m.From.AsTime()
	}
	if m.To != nil {
		to = m.To.AsTime()
	}
	res, err := backtestanalysis.Candles(dir, m.GetInstrument(), strings.ToUpper(strings.TrimSpace(m.GetTimeframe())), from, to, int(m.GetLimit()))
	if err != nil {
		return nil, analysisError(err)
	}
	return connect.NewResponse(res), nil
}

func (s analysisService) GetDecisions(_ context.Context, req *connect.Request[v1.BacktestGetDecisionsRequest]) (*connect.Response[v1.BacktestGetDecisionsResponse], error) {
	if !fromThisComputer(req.Peer()) {
		return nil, errNotLocal
	}
	dir, err := s.reportDir(req.Msg.GetPath())
	if err != nil {
		return nil, err
	}
	m := req.Msg
	q := backtestanalysis.DecisionQuery{Limit: int(m.GetLimit()), Kinds: m.GetKinds()}
	if m.Around != nil {
		q.Around = m.Around.AsTime()
	}
	if m.From != nil {
		q.From = m.From.AsTime()
	}
	if m.To != nil {
		q.To = m.To.AsTime()
	}
	if m.GetHasLeg() {
		leg := m.GetLeg()
		q.Leg = &leg
	}
	res, err := backtestanalysis.Decisions(dir, q)
	if err != nil {
		return nil, analysisError(err)
	}
	return connect.NewResponse(res), nil
}

