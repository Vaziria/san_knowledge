package san_research

import (
	"fmt"
	"strings"
)

// The pass rule for the trend approaches, fixed before their first run
// (approaches-2026-11-15/summary.md, section 2). A candidate is worth a
// DEMO forward-test only if every check passes.
const (
	ruleRealPF   = 1.2
	ruleHarshPF  = 1.05
	ruleWalkPF   = 1.1
	ruleYears    = 3 // profitable years needed, of the years run
	ruleMaxDD    = 30
	ruleMinTrade = 60
)

// Check is one line of the pass rule.
type Check struct {
	Name string
	Got  string
	Pass bool
}

// Verdict is the pass rule applied to one approach's rows.
type Verdict struct {
	Approach string
	Checks   []Check
	Pass     bool
}

func pfText(pf float64) string {
	if pf < 0 {
		return "inf"
	}
	return fmt.Sprintf("%.2f", pf)
}

// pfAbove: PF -1 (no losing trade) counts as above any threshold when
// there were trades.
func pfAbove(r BacktestRow, min float64) bool {
	if r.PF < 0 {
		return r.Trades > 0
	}
	return r.PF > min
}

// Judge applies the pass rule to the rows of one approach.
func Judge(approach string, rows []BacktestRow) Verdict {
	by := map[string]BacktestRow{}
	years, good := 0, 0
	for _, r := range rows {
		if r.Approach != approach {
			continue
		}
		by[r.Run] = r
		if len(r.Run) == 4 && r.Run[0] == '2' {
			years++
			if r.NetPct > 0 {
				good++
			}
		}
	}
	real, harsh, walk := by[runReal], by[runHarsh], by[runWalkOOS]
	_, hasWalk := by[runWalkOOS]
	v := Verdict{Approach: approach}
	add := func(name, got string, pass bool) { v.Checks = append(v.Checks, Check{name, got, pass}) }
	add(fmt.Sprintf("real PF > %.2f", ruleRealPF), pfText(real.PF), pfAbove(real, ruleRealPF))
	add(fmt.Sprintf("harsh PF > %.2f", ruleHarshPF), pfText(harsh.PF), pfAbove(harsh, ruleHarshPF))
	if hasWalk {
		add(fmt.Sprintf("walk-forward OOS PF > %.2f", ruleWalkPF), pfText(walk.PF), pfAbove(walk, ruleWalkPF))
	} else {
		add(fmt.Sprintf("walk-forward OOS PF > %.2f", ruleWalkPF), "not run", false)
	}
	add(fmt.Sprintf("profitable years >= %d", ruleYears), fmt.Sprintf("%d of %d", good, years), good >= ruleYears)
	add(fmt.Sprintf("max drawdown < %d%%", ruleMaxDD), fmt.Sprintf("%.1f%%", real.MaxDDPct), real.MaxDDPct < ruleMaxDD)
	add(fmt.Sprintf("trades >= %d", ruleMinTrade), fmt.Sprint(real.Trades), real.Trades >= ruleMinTrade)
	v.Pass = true
	for _, c := range v.Checks {
		v.Pass = v.Pass && c.Pass
	}
	return v
}

// TrendResults is backtests/results.md: one table per approach and the
// pass rule applied to each.
func TrendResults(rows []BacktestRow) string {
	var b strings.Builder
	var names []string
	seen := map[string]bool{}
	for _, r := range rows {
		if !seen[r.Approach] {
			seen[r.Approach] = true
			names = append(names, r.Approach)
		}
	}
	b.WriteString("# Trend approaches: backtest results\n\nGenerated by `san_research approaches` from san_backtest's cache. Pass rule: summary.md, section 2.\n\n")
	for _, n := range names {
		fmt.Fprintf(&b, "## %s\n\n| run | trades | win %% | PF | net %% | max DD %% | avg R | skipped |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n", n)
		for _, r := range rows {
			if r.Approach == n {
				fmt.Fprintf(&b, "| %s | %d | %.1f | %s | %.1f | %.1f | %.2f | %d |\n", r.Run, r.Trades, r.WinRate, pfText(r.PF), r.NetPct, r.MaxDDPct, r.AvgR, r.Skipped)
			}
		}
		if n == BenchmarkBuyHold {
			b.WriteString("\nBenchmark: not judged.\n\n")
			continue
		}
		v := Judge(n, rows)
		b.WriteString("\n| check | got | |\n| --- | --- | --- |\n")
		for _, c := range v.Checks {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", c.Name, c.Got, passWord(c.Pass))
		}
		if v.Pass {
			b.WriteString("\n**PASS: worth a DEMO forward-test.**\n\n")
		} else {
			b.WriteString("\n**FAIL: not worth a demo forward-test.**\n\n")
		}
	}
	return b.String()
}

func passWord(ok bool) string {
	if ok {
		return "PASS"
	}
	return "FAIL"
}
